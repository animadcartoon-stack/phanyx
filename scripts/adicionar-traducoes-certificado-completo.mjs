function setByPath(obj, dottedPath, value) {
  const parts = dottedPath.split(".");
  let current = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    const part = parts[i];
    if (!current[part] || typeof current[part] !== "object" || Array.isArray(current[part])) {
      current[part] = {};
    }
    current = current[part];
  }
  current[parts[parts.length - 1]] = value;
}

for (const locale of locales) {
  const file = path.join(process.cwd(), "messages", `${locale}.json`);
  const backup = `${file}.antes-certificado-completo.bak`;
  const original = fs.readFileSync(file, "utf8");
  const json = JSON.parse(original);

  if (!fs.existsSync(backup)) {
    fs.writeFileSync(backup, original, "utf8");
  }

  if (!json.AdminCertificateEditor || typeof json.AdminCertificateEditor !== "object") {
    json.AdminCertificateEditor = {};
  }

  for (const [key, value] of Object.entries(flatTranslations[locale])) {
    setByPath(json.AdminCertificateEditor, key, value);
  }

  for (const [key, value] of Object.entries(extraTranslations[locale] || {})) {
    setByPath(json.AdminCertificateEditor, key, value);
  }

  fs.writeFileSync(file, JSON.stringify(json, null, 2) + "\n", "utf8");
  console.log(`OK: ${locale}`);
}

