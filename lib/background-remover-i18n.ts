export function backgroundRemoverT(
  locale: LocalePhanyx,
  source: string,
  vars?: Record<string, string | number>
) {
  const translated =
    locale === "pt-BR"
      ? source
      : (translations[locale] as Record<string, string>)[source] ?? source;

  if (!vars) return translated;

  return Object.entries(vars).reduce(
    (value, [key, replacement]) =>
      value.replaceAll(`{${key}}`, String(replacement)),
    translated
  );
}
