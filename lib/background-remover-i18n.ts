export const backgroundRemoverLocales: LocalePhanyx[] = [
  "pt-BR", "pt-PT", "en-US", "es-ES", "fr-FR",
];

export function backgroundRemoverPath(locale: string) {
  const safe = backgroundRemoverLocales.includes(locale as LocalePhanyx)
    ? (locale as LocalePhanyx)
    : "pt-BR";
  return safe === "pt-BR"
    ? "/removedor-de-fundo"
    : `/${safe}/${backgroundRemoverSlugs[safe]}`;
}

export function backgroundRemoverLocaleFromSlug(
  market: string,
  slug: string
): LocalePhanyx | null {
  if (!backgroundRemoverLocales.includes(market as LocalePhanyx)) return null;
  const locale = market as LocalePhanyx;
  if (locale === "pt-BR") return null;
  return backgroundRemoverSlugs[locale] === slug ? locale : null;
}

export function backgroundRemoverAlternates() {
  return {
    canonical: backgroundRemoverPath("pt-BR"),
    languages: {
      ...Object.fromEntries(
        backgroundRemoverLocales.map((locale) => [
          locale,
          backgroundRemoverPath(locale),
        ])
      ),
      "x-default": backgroundRemoverPath("pt-BR"),
    } as Record<LocalePhanyx | "x-default", string>,
  };
}

